/**
 * Points this checkout at a real Firebase project.
 *
 *   node scripts/link-firebase.mjs <PROJECT_ID>
 *   make firebase-link PROJECT_ID=<PROJECT_ID>
 *
 * Writes `.firebaserc`, writes `.env.production.local` for local production
 * builds, and prints the exact GitHub variables the deploy workflow expects.
 *
 * The config is pulled from the project with `firebase apps:sdkconfig` rather than
 * copied out of the console by hand: six values transcribed by eye is the most
 * likely place for this setup to go quietly wrong, and a single wrong character
 * produces a site that builds cleanly and then fails in every visitor's browser.
 */

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const projectId = process.argv[2];

if (!projectId) {
  console.error("Usage: node scripts/link-firebase.mjs <PROJECT_ID>");
  process.exit(1);
}

if (!/^[a-z0-9-]{4,60}$/.test(projectId)) {
  console.error(
    `"${projectId}" does not look like a Firebase project id ` +
      "(lower-case letters, digits and hyphens).",
  );
  process.exit(1);
}

const FIREBASE = ["--yes", "firebase-tools@13"];

function firebase(args) {
  return execFileSync("npx", [...FIREBASE, ...args], {
    encoding: "utf8",
    stdio: ["inherit", "pipe", "pipe"],
  });
}

// --- Fetch the web app config -------------------------------------------
console.log(`→ fetching web config for ${projectId}`);

let sdkConfig;
try {
  const raw = firebase(["apps:sdkconfig", "WEB", "--project", projectId, "--json"]);
  const parsed = JSON.parse(raw);
  sdkConfig = parsed?.result?.sdkConfig;
  if (!sdkConfig) throw new Error("no sdkConfig in response");
} catch (error) {
  const message = String(error.stderr || error.message || error);

  console.error("\n✖ Could not read the web app config.\n");

  if (/no app/i.test(message) || /No WEB app/i.test(message)) {
    console.error("The project has no registered web app yet. Create one:\n");
    console.error(`  npx firebase-tools@13 apps:create WEB FORGE --project ${projectId}\n`);
  } else if (/not logged in|authentication|credentials/i.test(message)) {
    console.error("You are not signed in to the Firebase CLI:\n");
    console.error("  npx firebase-tools@13 login\n");
  } else {
    console.error(message.trim().split("\n").slice(0, 8).join("\n"), "\n");
  }

  process.exit(1);
}

// --- .firebaserc ---------------------------------------------------------
// A single project, so no aliases: an unused "production" alias pointing at a
// project that does not exist is a trap for whoever runs a deploy next.
writeFileSync(
  ".firebaserc",
  `${JSON.stringify({ projects: { default: projectId } }, null, 2)}\n`,
  "utf8",
);
console.log("✓ .firebaserc → " + projectId);

// --- .env.production.local ----------------------------------------------
const env = {
  NEXT_PUBLIC_FIREBASE_API_KEY: sdkConfig.apiKey,
  NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN: sdkConfig.authDomain,
  NEXT_PUBLIC_FIREBASE_PROJECT_ID: sdkConfig.projectId,
  NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET: sdkConfig.storageBucket,
  NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID: sdkConfig.messagingSenderId,
  NEXT_PUBLIC_FIREBASE_APP_ID: sdkConfig.appId,
};

const missing = Object.entries(env)
  .filter(([, value]) => !value)
  .map(([key]) => key);

if (missing.length > 0) {
  console.error(`\n✖ The project returned an incomplete config: ${missing.join(", ")}`);
  process.exit(1);
}

writeFileSync(
  ".env.production.local",
  [
    "# Generated by `make firebase-link`. Git-ignored.",
    "#",
    "# Used by production builds on this machine (`make preview`). Local development",
    "# ignores these entirely and talks to the emulator instead.",
    "",
    ...Object.entries(env).map(([key, value]) => `${key}=${value}`),
    "NEXT_PUBLIC_USE_FIREBASE_EMULATOR=false",
    "",
  ].join("\n"),
  "utf8",
);
console.log("✓ .env.production.local written (git-ignored)");

// --- What GitHub needs ---------------------------------------------------
console.log(`
────────────────────────────────────────────────────────────────
 GitHub → Settings → Secrets and variables → Actions → Variables
────────────────────────────────────────────────────────────────`);
console.log(`  FIREBASE_PROJECT_ID                       ${projectId}`);
for (const [key, value] of Object.entries(env)) {
  if (key === "NEXT_PUBLIC_FIREBASE_PROJECT_ID") continue; // derived in the workflow
  console.log(`  ${key.padEnd(41)} ${value}`);
}
console.log(`
 Or set all six at once:

   make gh-config

 Then add the one Secret (the service-account JSON):

   make gh-secret KEY=~/Downloads/<project>-<hash>.json
────────────────────────────────────────────────────────────────
`);
